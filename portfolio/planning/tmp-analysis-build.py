# ── TOC doc template ─────────────────────────────────────────────────
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            self.notify("TOCEntry", (getattr(flowable, "bookmark_level", 0),
                                     getattr(flowable, "bookmark_text", ""),
                                     self.page,
                                     getattr(flowable, "bookmark_key", "")))

def add_heading(html, toc_text, style, level):
    key = "h_" + hashlib.md5(toc_text.encode("utf-8")).hexdigest()[:8]
    p = Paragraph('<a name="%s"/>%s' % (key, html), style)
    p.bookmark_name = toc_text
    p.bookmark_level = level
    p.bookmark_text = toc_text
    p.bookmark_key = key
    return p

def callout(label, text, bg=CARD_BG, bar=ACCENT):
    para = Paragraph('<b><font color="%s">%s</font></b>%s' % (ACC_HEX, label, text),
                     S["callout"])
    t = Table([[para]], colWidths=[AVAIL - 8], hAlign="CENTER")
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), bg),
        ("LINEBEFORE", (0, 0), (0, -1), 2.5, bar),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
    ]))
    return t

