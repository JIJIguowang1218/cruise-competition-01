OUT = r"C:\Users\86136\Desktop\C26答辩逐字稿-打印版2页.docx"

doc = Document()

sec = doc.sections[0]
sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
sec.top_margin = sec.bottom_margin = Cm(0.4)
sec.left_margin = sec.right_margin = Cm(0.4)
sec.footer_distance = Cm(0.2)

def set_east_asia(run, ea_name):
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn('w:rFonts'))
    if rfonts is None:
        rfonts = OxmlElement('w:rFonts')
        rpr.append(rfonts)
    rfonts.set(qn('w:eastAsia'), ea_name)

normal = doc.styles['Normal']
normal.font.name = 'Times New Roman'
normal.font.size = Pt(12)
normal.element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')

for i, (pid, name, text) in enumerate(SECTIONS):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.12
    pf.space_before = Pt(4 if i else 0)
    pf.space_after = Pt(0)

    r = p.add_run(f"【{pid}·{name}】")
    r.bold = True
    r.font.size = Pt(12)
    r.font.name = 'Arial'
    r.font.color.rgb = RGBColor(0x1F, 0x3B, 0x63)
    set_east_asia(r, '黑体')

    rb = p.add_run(text)
    rb.font.size = Pt(12)
    rb.font.name = 'Times New Roman'
    set_east_asia(rb, '宋体')

doc.save(OUT)
print('saved', OUT)
